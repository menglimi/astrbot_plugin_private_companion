"""Build workspaces and optionally publish the V2-owned cottage to the preview.

V2 pages/陪伴小屋 is canonical. Standalone workspaces are copied into its asset
scope. --check compares generated files without writing; --preview is optional.
"""
import argparse
import hashlib
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "pages" / "陪伴小屋"
PREVIEW = ROOT.parent / "astrbot_plugin_content_companion" / "design-previews" / "companion-v2"
WORKSPACES = {"host": "宿主管理", "life": "日记与生活", "relationships": "关系与记忆", "identity": "关系与权限",
              # 人格问卷编辑版本化草稿，不写宿主人格；源码仍在既有工作区目录中。
              "persona": "人物设定工坊", "designer": "新的她"}
TEXT = {".js", ".css", ".html", ".md", ".json"}


def normalized_payload(path, payload):
    """Use the same UTF-8 and newline contract as the release builder."""
    if path.suffix.lower() not in TEXT:
        return payload
    text = payload.decode("utf-8-sig").replace("\r\n", "\n").replace("\r", "\n")
    return (text.rstrip("\n") + "\n").encode("utf-8")


def publish(*, check=False, preview=None):
    changed = []

    def emit(path, payload):
        payload = normalized_payload(path, payload)
        if not path.exists() or path.read_bytes() != payload:
            changed.append(str(path.relative_to(ROOT)) if path.is_relative_to(ROOT) else str(path))
            if not check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_bytes(payload)
        return payload

    projected = {}
    bundles = {}
    # Only palette declarations belong in embedded workspaces. Their own layout
    # and appearance dimensions remain authoritative.
    tokens = (SOURCE / "tokens.css").read_text(encoding="utf-8-sig")
    palette = "\n".join(match.group(0) for match in re.finditer(r"[^{}]+\{[^{}]+\}", tokens)
                        if "--t-canvas:" in match.group(0))
    workspace_theme = (SOURCE / "workspace-theme.css").read_text(encoding="utf-8-sig")
    for name, source in WORKSPACES.items():
        source_root = ROOT / "pages" / source
        html = (source_root / "workspace.html").read_text(encoding="utf-8-sig")
        bridge = (SOURCE / "embedded-bridge.js").read_text(encoding="utf-8-sig")
        js = (source_root / "app.js").read_text(encoding="utf-8-sig")
        extras = (["member-editor.js"] if name == "identity" else
                  ["group-memory.js"] if name == "relationships" else [])
        if extras:
            js = (SOURCE / "assets" / "lucide.min.js").read_text(encoding="utf-8-sig") + "\n" + "\n".join(
                (source_root / filename).read_text(encoding="utf-8-sig") for filename in extras) + "\n" + js
        css = (source_root / "style.css").read_text(encoding="utf-8-sig")
        html = re.sub(r'<script[^>]*src="[^"]+"[^>]*></script>', "", html)
        html = html.replace('<link rel="stylesheet" href="style.css">',
                            "<style>" + css + "\n" + palette + "\n" + workspace_theme + "</style>")
        html = html.replace("</body>", "<script>" + (bridge + "\n" + js).replace("</script", "<\\/script") + "</script></body>")
        bundles[name] = html
        for filename in ("index.html", "app.js", "style.css", *extras):
            source_filename = "workspace.html" if filename == "index.html" else filename
            payload = (ROOT / "pages" / source / source_filename).read_bytes()
            if filename == "index.html":
                html = payload.decode("utf-8-sig").replace(
                    '<script src="/api/plugin/page/bridge-sdk.js" defer></script>',
                    '<script src="../../embedded-bridge.js" defer></script>')
                html = html.replace('../陪伴小屋/assets/lucide.min.js', '../../assets/lucide.min.js')
                payload = html.encode("utf-8")
            destination = SOURCE / "workspaces" / name / filename
            projected[destination.relative_to(SOURCE).as_posix()] = emit(destination, payload)

    for name, html in bundles.items():
        payload = ("// Generated by tools/sync_framework_page.py; source workspaces remain editable.\n"
                   "window.CompanionWorkspaceBundle=window.CompanionWorkspaceBundle||{};\n"
                   "window.CompanionWorkspaceBundle[" + json.dumps(name) + "]="
                   + json.dumps(html, ensure_ascii=False) + ";\n").encode("utf-8")
        projected[f"workspace-bundles/{name}.js"] = emit(SOURCE / "workspace-bundles" / f"{name}.js", payload)

    # One deterministic stylesheet avoids 40+ HTTP requests before the boot
    # gate can reveal the page.  Keep the source order in css-sources.json; the
    # generated bundle stays in the same directory so relative url() values are
    # unchanged.
    css_sources = json.loads((SOURCE / "css-sources.json").read_text(encoding="utf-8-sig"))
    css_parts = []
    for name in css_sources:
        css_path = SOURCE / str(name)
        css_text = css_path.read_text(encoding="utf-8-sig").replace("\r\n", "\n").replace("\r", "\n")
        css_text = re.sub(r"^\s*@charset\s+[^;]+;\s*\n?", "", css_text, flags=re.IGNORECASE | re.MULTILINE)
        css_parts.append(f"/* {name} */\n{css_text.strip()}\n")
    bundle_css = "\n".join(css_parts).rstrip("\n") + "\n"
    bundle_hash = hashlib.sha256(bundle_css.encode("utf-8")).hexdigest()[:16]
    projected["bundle.css"] = emit(SOURCE / "bundle.css", bundle_css.encode("utf-8"))
    index_path = SOURCE / "index.html"
    index_text = index_path.read_text(encoding="utf-8-sig")
    index_text = re.sub(r"bundle\.css\?v=[^\"]+", f"bundle.css?v={bundle_hash}", index_text)
    projected["index.html"] = emit(index_path, index_text.encode("utf-8"))

    files = {p.relative_to(SOURCE).as_posix(): normalized_payload(p, p.read_bytes())
             for p in sorted(SOURCE.rglob("*"))
             if p.is_file() and p.name not in {"page-build.json", "shell-preview.html", "shell-preview-mock.html"}
             and p.suffix.lower() not in {".bak", ".backup"} and "__pycache__" not in p.parts}
    files.update(projected)
    hashes = {name: hashlib.sha256(payload).hexdigest() for name, payload in sorted(files.items())}
    manifest = (json.dumps({"source": "astrbot_plugin_private_companion/pages/陪伴小屋",
        "workspaces": WORKSPACES, "files": hashes}, ensure_ascii=False, indent=2) + "\n").encode("utf-8")
    emit(SOURCE / "page-build.json", manifest)
    if preview is not None:
        preview = Path(preview).resolve()
        for name, payload in files.items():
            destination = (preview / name).resolve()
            if not destination.is_relative_to(preview):
                raise ValueError("preview assets must remain inside the destination")
            if name == "index.html":
                payload = payload.decode("utf-8").replace(
                    '  <meta name="companion-api-host" content="astrbot_plugin_private_companion">\n', "").encode("utf-8")
            emit(destination, payload)
        emit(preview / "page-build.json", manifest)
    return changed


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--preview", nargs="?", type=Path, const=PREVIEW)
    args = parser.parse_args()
    changed = publish(check=args.check, preview=args.preview)
    print(json.dumps({"mode": "check" if args.check else "publish", "changed": changed}, ensure_ascii=False))
    return 1 if args.check and changed else 0


if __name__ == "__main__":
    raise SystemExit(main())
